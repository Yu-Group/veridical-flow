"""Render the hand-written docs pages from a shared shell.

The article pages (`agents.html`, `vflow-internals.html`) are written by hand
rather than generated by pdoc. Only the article body of each lives in
`pages/<name>.html`; the page shell around it (stylesheets, the header bar and
the whole left-hand sidebar) is lifted straight out of the generated
`index.html`, so the articles always show exactly what the API pages show.

Run it after pdoc has produced index.html (`hatch run docs:build` does this):

    python build_pages.py
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))

# name -> (title, extra <head> content)
PAGES = {
    "agents": ("vflow for agents", ""),
    "vflow-internals": ("How vflow works internally", ""),
}


def _read(path):
    with open(os.path.join(HERE, path), encoding="utf-8") as f:
        return f.read()


def shared_head(index_html, title, extra):
    """The index page's <head>, retitled for this page."""
    head = index_html[index_html.index("<head>") : index_html.index("</head>")]
    title_tag = f"<title>vflow &middot; {title}</title>"
    head = re.sub(r"<title>.*?</title>", title_tag, head, flags=re.S)
    return head.rstrip() + "\n" + extra + "</head>"


def shared_block(index_html, start_tag, end_tag):
    start = index_html.index(start_tag)
    end = index_html.index(end_tag, start) + len(end_tag)
    return index_html[start:end]


def shared_sidebar(index_html):
    """The index page's sidebar, with its in-page anchors pointed back at it."""
    nav = shared_block(index_html, '<nav id="sidebar">', "</nav>")
    return re.sub(r'href="#', 'href="index.html#', nav)


def main():
    index_html = _read("index.html")
    header = shared_block(index_html, '<header id="site-header">', "</header>")
    sidebar = shared_sidebar(index_html)
    footer = shared_block(index_html, '<footer id="footer">', "</footer>")
    for name, (title, extra) in PAGES.items():
        content = _read(os.path.join("pages", f"{name}.html")).strip()
        page = (
            '<!doctype html>\n<html lang="en">\n\n'
            + shared_head(index_html, title, extra)
            + "\n\n<body>\n"
            + header
            + '\n<main>\n<article id="content">\n'
            + content
            + "\n</article>\n"
            + sidebar
            + "\n</main>\n\n"
            + footer
            + "\n</body>\n</html>\n"
        )
        with open(os.path.join(HERE, f"{name}.html"), "w", encoding="utf-8") as f:
            f.write(page)
        print(f"  wrote {name}.html")


if __name__ == "__main__":
    main()
